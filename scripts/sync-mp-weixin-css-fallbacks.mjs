/**
 * @module sync-mp-weixin-css-fallbacks
 * @lang zh-CN 从默认浅色主题解析受限 token，并为每个组件 CSS 生成 `var(--u-*, literal)` 回退声明。当前小程序编译路径缺少可继承 token 时使用字面值，H5 仍以已有 token 值为准。
 * @lang en Resolves bounded tokens from the default light theme and generates `var(--u-*, literal)` fallback declarations for each component CSS file. The current Mini Program compilation path uses the literal when it lacks an inheritable token, while H5 continues to use an existing token value.
 */

import { readdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const themePath = join(repositoryRoot, 'HIA-uView-UI/src/theme/hia-light.css');
const componentDirectory = join(repositoryRoot, 'HIA-uView-UI/src/components');
const fallbackDocumentationStart = '/* <lang><zh-CN>以下 custom property 回退由 sync-mp-weixin-css-fallbacks 依据默认主题生成；每个 var() 的 fallback 仅在组件作用域缺少 token 时生效，已有 token 的平台仍保持动态主题语义。</zh-CN><en>The custom-property fallbacks below are generated from the default theme by sync-mp-weixin-css-fallbacks; each var() fallback applies only when the component scope lacks the token, while platforms with the token retain dynamic-theme semantics.</en></lang> */';
const fallbackStart = '/* HIA-uView MP-Weixin literal fallback start: generated, do not edit manually. */';
const fallbackEnd = '/* HIA-uView MP-Weixin literal fallback end. */';
const writeMode = process.argv.includes('--write');

/**
 * @lang zh-CN 从主题 CSS 中读取全部自定义属性的原始值；此函数只读取受版本控制的默认主题，不扫描调用方目录或环境变量。
 * @lang en Reads raw values for every custom property from the theme CSS; this function reads only the version-controlled default theme and scans neither caller directories nor environment variables.
 * @param {string} themeSource <lang><zh-CN>默认主题的完整 CSS 文本。</zh-CN><en>Complete CSS text of the default theme.</en></lang>
 * @returns {Map<string, string>} <lang><zh-CN>token 名称到未经递归替换的 CSS 值映射。</zh-CN><en>Mapping from token names to CSS values before recursive substitution.</en></lang>
 */
function readThemeTokens(themeSource) {
  const tokens = new Map();
  const tokenPattern = /(^|[;\n])\s*(--u-[\w-]+)\s*:\s*([^;{}]+);/g;

  for (const match of themeSource.matchAll(tokenPattern)) {
    // <lang><zh-CN>token 值保留原 CSS 表达式，递归解析在后续独立步骤完成，便于报告缺失或循环引用。</zh-CN><en>Retains the original CSS expression for each token; recursive resolution happens in a separate later step so missing or cyclic references can be reported.</en></lang>
    tokens.set(match[2], match[3].trim());
  }

  return tokens;
}

/**
 * @lang zh-CN 递归把一个 CSS 值内的受限 `var(--u-*)` 替换为默认主题字面值；不解释任意函数、URL、外部输入或调用方 token。
 * @lang en Recursively replaces bounded `var(--u-*)` references inside one CSS value with default-theme literals; it interprets no arbitrary function, URL, external input, or caller token.
 * @param {string} value <lang><zh-CN>待解析的 CSS 声明值。</zh-CN><en>CSS declaration value to resolve.</en></lang>
 * @param {Map<string, string>} tokens <lang><zh-CN>默认主题 token 映射。</zh-CN><en>Default-theme token mapping.</en></lang>
 * @param {string[]} [chain=[]] <lang><zh-CN>当前递归链，仅用于检测循环引用。</zh-CN><en>Current recursion chain, used only to detect cycles.</en></lang>
 * @returns {string | null} <lang><zh-CN>不含主题 token 引用的字面 CSS 值；声明混入组件运行时局部变量时返回 null。</zh-CN><en>Literal CSS value containing no theme-token reference, or null when a declaration mixes in a component-runtime local variable.</en></lang>
 */
function resolveTokenValue(value, tokens, chain = []) {
  return value.replace(/var\(\s*(--u-[\w-]+)\s*\)/g, (reference, tokenName) => {
    // <lang><zh-CN>组件运行时局部变量（如受限 padding 或行数）不能由默认主题静态替代；保留它们给组件自己的受控内联样式路径，而不是猜测一个主题值。</zh-CN><en>Component-runtime local variables (such as bounded padding or line count) cannot be statically replaced by the default theme; leave them to their component-owned controlled inline-style path rather than guessing a theme value.</en></lang>
    if (!tokens.has(tokenName)) {
      return reference;
    }
    if (chain.includes(tokenName)) {
      throw new Error(`Circular default-theme token reference: ${[...chain, tokenName].join(' -> ')}.`);
    }

    return resolveTokenValue(tokens.get(tokenName), tokens, [...chain, tokenName]);
  });
}

/**
 * @lang zh-CN 去掉脚本上次生成的回退区块，保留维护者编写的原组件 CSS；该函数只接受明确的成对 marker，并一并移除紧邻 marker 的生成说明，避免删除普通注释或规则。
 * @lang en Removes the fallback block generated by a prior script run while retaining maintainer-authored component CSS; this function accepts only explicit paired markers and also removes the generated note immediately adjoining the marker, never ordinary comments or rules.
 * @param {string} source <lang><zh-CN>组件 CSS 全文。</zh-CN><en>Complete component CSS text.</en></lang>
 * @returns {string} <lang><zh-CN>不含旧生成区块的组件 CSS。</zh-CN><en>Component CSS without a prior generated block.</en></lang>
 */
function removeGeneratedFallback(source) {
  const markerIndex = source.indexOf(fallbackStart);
  if (markerIndex === -1) {
    return source.trimEnd();
  }

  // <lang><zh-CN>生成说明总是紧邻 start marker；用最后一个双语注释起点兼容前一生成版本的说明文字，同时不读取/删除 marker 前更早的源码规则。</zh-CN><en>The generated note always immediately adjoins the start marker; using the last bilingual-comment start supports the prior generated-note wording while neither reading nor deleting earlier authored rules before the marker.</en></lang>
  const documentedStart = source.lastIndexOf('/* <lang>', markerIndex);
  const startIndex = documentedStart === -1 ? markerIndex : documentedStart;

  const endIndex = source.indexOf(fallbackEnd, markerIndex);
  if (endIndex === -1) {
    throw new Error('Generated Mini Program fallback start marker has no matching end marker.');
  }

  return source.slice(0, startIndex).trimEnd();
}

/**
 * @lang zh-CN 从一个普通 CSS 规则中提取含默认主题 token 的声明，并在同一 selector 下生成带 `var()` fallback 参数的兼容规则。当前组件 CSS 不含嵌套规则，遇到嵌套会由检查器拒绝而非错误改写。
 * @lang en Extracts default-theme-token declarations from one ordinary CSS rule and generates a compatibility rule under the same selector with `var()` fallback arguments. Current component CSS contains no nested rules; a nested rule is rejected by the checker rather than rewritten incorrectly.
 * @param {string} selector <lang><zh-CN>原 CSS selector 文本。</zh-CN><en>Original CSS selector text.</en></lang>
 * @param {string} body <lang><zh-CN>该 selector 的未嵌套声明体。</zh-CN><en>Unnested declaration body for the selector.</en></lang>
 * @param {Map<string, string>} tokens <lang><zh-CN>默认主题 token 映射。</zh-CN><en>Default-theme token mapping.</en></lang>
 * @returns {string | null} <lang><zh-CN>生成的回退规则；没有 token 声明时为 null。</zh-CN><en>Generated fallback rule, or null when no declaration uses a token.</en></lang>
 */
function buildFallbackRule(selector, body, tokens) {
  // <lang><zh-CN>原样式的双语说明注释属于源码文档，不应复制到生成规则的 selector 前；仅保留实际 selector，避免生成区块重复 API 文档。</zh-CN><en>Bilingual explanatory comments in authored styles belong to source documentation and must not be copied before a generated-rule selector; retain only the actual selector to avoid duplicated API docs in the generated block.</en></lang>
  const normalizedSelector = selector.replace(/\/\*[\s\S]*?\*\//g, '').trim();
  if (normalizedSelector.length === 0) {
    return null;
  }

  const declarations = [];
  const declarationPattern = /([\w-]+)\s*:\s*([^;{}]+);/g;

  for (const match of body.matchAll(declarationPattern)) {
    const property = match[1];
    const originalValue = match[2].trim();
    if (!originalValue.includes('var(--u-')) {
      continue;
    }

    const literalValue = resolveTokenValue(originalValue, tokens);
    if (literalValue.includes('var(--u-')) {
      // <lang><zh-CN>含局部运行时变量的声明不生成主题字面值回退；其动态语义必须由对应组件单独且受限地投影。</zh-CN><en>A declaration containing a local runtime variable receives no theme-literal fallback; its dynamic semantics must be projected separately and in a bounded way by the owning component.</en></lang>
      continue;
    }

    // <lang><zh-CN>把每个主题 token 写成原 token + 默认主题 fallback 的单一 CSS var() 声明；这不会让后续未解析 token 覆盖前置字面值，也不会替换有 token runtime 的动态结果。</zh-CN><en>Writes every theme token as one CSS var() declaration with the original token plus a default-theme fallback; this neither lets a later unresolved token override a prior literal nor replaces the dynamic result in a runtime that has the token.</en></lang>
    const fallbackValue = originalValue.replace(/var\(\s*(--u-[\w-]+)\s*\)/g, (reference, tokenName) => {
      const tokenLiteral = resolveTokenValue(tokens.get(tokenName), tokens, [tokenName]);
      return `var(${tokenName}, ${tokenLiteral})`;
    });
    declarations.push(`  ${property}: ${fallbackValue};`);
  }

  return declarations.length > 0 ? `${normalizedSelector} {\n${declarations.join('\n')}\n}` : null;
}

/**
 * @lang zh-CN 为一个组件 CSS 生成完整回退区块；仅处理简单顶层规则，以当前受控组件样式表的已声明结构为边界。
 * @lang en Generates the complete fallback block for one component CSS file; processes simple top-level rules only, bounded by the declared structure of current controlled component stylesheets.
 * @param {string} source <lang><zh-CN>不含旧生成区块的组件 CSS。</zh-CN><en>Component CSS without a prior generated block.</en></lang>
 * @param {Map<string, string>} tokens <lang><zh-CN>默认主题 token 映射。</zh-CN><en>Default-theme token mapping.</en></lang>
 * @returns {string} <lang><zh-CN>包含新生成区块的完整组件 CSS。</zh-CN><en>Complete component CSS including the newly generated block.</en></lang>
 */
function addGeneratedFallback(source, tokens) {
  const fallbackRules = [];
  const rulePattern = /([^{}]+)\{([^{}]*)\}/g;

  for (const match of source.matchAll(rulePattern)) {
    const fallbackRule = buildFallbackRule(match[1], match[2], tokens);
    if (fallbackRule !== null) {
      fallbackRules.push(fallbackRule);
    }
  }

  if (fallbackRules.length === 0) {
    return `${source.trimEnd()}\n`;
  }

  return `${source.trimEnd()}\n\n${fallbackDocumentationStart}\n${fallbackStart}\n${fallbackRules.join('\n\n')}\n${fallbackEnd}\n`;
}

/**
 * @lang zh-CN 枚举每个 `u-*` 组件目录中与目录同名的主样式表；不递归扫描任意 CSS，避免把 fixture、文档或第三方文件纳入生成范围。
 * @lang en Enumerates the primary same-named stylesheet in each `u-*` component directory; it recursively scans no arbitrary CSS, preventing fixtures, docs, or third-party files from entering the generation scope.
 * @returns {Promise<string[]>} <lang><zh-CN>按字典序排列的受控组件 CSS 绝对路径。</zh-CN><en>Lexically sorted absolute paths of controlled component CSS files.</en></lang>
 */
async function findComponentStyles() {
  const entries = await readdir(componentDirectory, { withFileTypes: true });
  return entries
    .filter((entry) => entry.isDirectory() && entry.name.startsWith('u-'))
    .map((entry) => join(componentDirectory, entry.name, `${entry.name}.css`))
    .sort((left, right) => left.localeCompare(right));
}

/**
 * @lang zh-CN 同步或检查所有组件字面值回退；默认模式只读并以非零失败报告漂移，`--write` 是维护者显式执行的确定性源码生成步骤。
 * @lang en Synchronizes or checks all component literal fallbacks; default mode is read-only and reports drift with failure, while `--write` is an explicit maintainer-invoked deterministic source-generation step.
 * @returns {Promise<void>} <lang><zh-CN>无返回值；发现漂移、缺失 token 或不受支持的结构时抛出错误。</zh-CN><en>Resolves without a value and throws on drift, missing tokens, or unsupported structure.</en></lang>
 */
async function syncFallbacks() {
  const [themeSource, stylePaths] = await Promise.all([
    readFile(themePath, 'utf8'),
    findComponentStyles()
  ]);
  const tokens = readThemeTokens(themeSource);
  const stalePaths = [];

  for (const stylePath of stylePaths) {
    // <lang><zh-CN>每次只读取/比较一个已声明样式表；写模式仅改写计算结果不同的同一受控文件。</zh-CN><en>Reads and compares one declared stylesheet at a time; write mode rewrites only the same controlled file when its computed result differs.</en></lang>
    const currentSource = await readFile(stylePath, 'utf8');
    const expectedSource = addGeneratedFallback(removeGeneratedFallback(currentSource), tokens);
    if (currentSource === expectedSource) {
      continue;
    }

    stalePaths.push(stylePath);
    if (writeMode) {
      await writeFile(stylePath, expectedSource, 'utf8');
    }
  }

  if (stalePaths.length > 0 && !writeMode) {
    throw new Error(`Mini Program CSS literal fallbacks are stale:\n${stalePaths.map((stylePath) => `- ${stylePath.slice(repositoryRoot.length + 1)}`).join('\n')}\nRun: npm run theme:sync`);
  }

  console.log(writeMode ? `Synchronized Mini Program CSS literal fallbacks for ${stalePaths.length} component stylesheet(s).` : 'HIA-uView Mini Program CSS literal fallback contract passed.');
}

await syncFallbacks();
